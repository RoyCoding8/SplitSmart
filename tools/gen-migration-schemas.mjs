// Regenerates app/src/test/java/com/splitsmart/data/MigrationSchemas.kt from the
// Room schemas KSP exports to app/schemas/.
//
// The migration tests need a database shaped exactly like the one a user had
// before the upgrade. Those shapes are already written down, by Room, in
// app/schemas/com.splitsmart.data.AppDatabase/<v>.json. This script turns each
// one into the DDL a test executes, so a test cannot be pinned to a schema that
// Room never shipped.
//
//   node tools/gen-migration-schemas.mjs
//
// Run it after any schema change. Adding a version appends to the output; it
// never rewrites the DDL of an older version, which is what a migration test
// depends on.

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaDir = join(root, "app", "schemas", "com.splitsmart.data.AppDatabase");
const outFile = join(
  root,
  "app",
  "src",
  "test",
  "java",
  "com",
  "splitsmart",
  "data",
  "MigrationSchemas.kt"
);

// A virtual table's createSql is the only statement whose name is not the entity
// name, and the FTS sync triggers name their shadow tables in the SQL itself.
const named = (sql, table) => sql.replaceAll("${TABLE_NAME}", table);

function ddlFor(version) {
  const schema = JSON.parse(
    readFileSync(join(schemaDir, `${version}.json`), "utf8")
  ).database;
  const statements = [];
  for (const entity of schema.entities) {
    statements.push(named(entity.createSql, entity.tableName));
    for (const index of entity.indices ?? []) {
      statements.push(named(index.createSql, entity.tableName));
    }
    for (const trigger of entity.contentSyncTriggers ?? []) {
      statements.push(named(trigger, entity.tableName));
    }
  }
  if (statements.length === 0) throw new Error(`version ${version} has no DDL`);
  return statements;
}

const versions = readdirSync(schemaDir)
  .filter((f) => f.endsWith(".json"))
  .map((f) => Number.parseInt(f, 10))
  .sort((a, b) => a - b);

const body = versions
  .map((v) => {
    const lines = ddlFor(v).map((s) => `  "${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`);
    return `internal val SCHEMA_${v}: List<String> =\n    listOf(\n${lines.join(",\n")})`;
  })
  .join("\n\n");

const lookup =
  `/** Every exported version, so a test can name the one it starts from. */\n` +
  `internal val SCHEMAS: Map<Int, List<String>> =\n    mapOf(\n` +
  versions.map((v) => `        ${v} to SCHEMA_${v},`).join("\n") +
  `\n    );\n`;

const file = `package com.splitsmart.data

/**
 * The schema a real database had at each version, as the DDL that version's
 * exported [app/schemas] record. Room writes those files on every build.
 *
 * A migration test is only as good as the database it starts from, and Room
 * validates the whole schema on open: a fixture missing a table or an index fails
 * for a reason that has nothing to do with the migration under test. So the
 * fixture is these statements, not a hand-transcribed copy of them.
 *
 * Generated by tools/gen-migration-schemas.mjs. Do not edit.
 */
${body}

${lookup}
`;

const total = versions.map((v) => ddlFor(v).length).reduce((a, b) => a + b, 0);
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, file);
console.log(`wrote ${outFile} -- ${versions.length} versions, ${total} statements`);
